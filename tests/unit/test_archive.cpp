// The same pseudo text the generator wrote.
std::string content(size_t n) {
    std::string s;
    for (size_t i = 0; i < n; ++i) s.push_back(i % 11 ? static_cast<char>(97 + ((i * i + i / 7) % 26)) : ' ');
    return s;
}

std::string slurp(const fs::path &p) {
    std::ifstream f(p, std::ios::binary);
    return std::string((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
}

fs::path fresh_dir(const char *name) {
    const fs::path d = fs::temp_directory_path() / name;
    std::error_code ec;
    fs::remove_all(d, ec);
    fs::create_directories(d);
    return d;
}

void check_extracted(const fs::path &dir) {
    CHECK(slurp(dir / "readme.txt") == content(3000));
    CHECK(slurp(dir / "bin" / "tool") == content(700));
    CHECK(fs::exists(dir / "empty.txt"));
    CHECK(fs::file_size(dir / "empty.txt") == 0);
}

